def _read_varint(data: bytes, index: int) -> Tuple[int, int]:
    """读取一个 LEB128 varint，返回 (值, 新下标)。"""
    value = 0
    shift = 0
    while True:
        byte = data[index]
        index += 1
        value |= (byte & 0x7F) << shift
        if byte & 0x80:
            shift += 7
        else:
            return value, index


@functools.lru_cache(maxsize=None)
def _gb18030_first_letters() -> Dict[int, str]:
    """解压内置表，返回 {码位: 首字母}。"""
    raw = zlib.decompress(base64.b64decode(_GB18030_TABLE_B64))
    table: Dict[int, str] = {}
    index = 0
    while index < len(raw):
        letter = chr(raw[index])
        index += 1
        size, index = _read_varint(raw, index)
        codepoint = 0
        for _ in range(size):
            delta, index = _read_varint(raw, index)
            codepoint += delta
            table[codepoint] = letter
    return table


def _gb18030_letter(char: str) -> Optional[str]:
    """查内置 GB18030 首字母表，未收录返回 None。"""
    code = ord(char)
    if code == 0x3007:  # 〇
        return _gb18030_first_letters().get(code)
    # 只有汉字区间才查表，避免把标点/符号误认
    if not (
        0x4E00 <= code <= 0x9FFF
        or 0x3400 <= code <= 0x4DBF
        or 0xF900 <= code <= 0xFAFF
        or 0x20000 <= code <= 0x2FA1F
    ):
        return None
    return _gb18030_first_letters().get(code)


def first_letter(text: Optional[str], fallback: str = "#") -> str:
    """
    计算标题首字母。

    :param text: 标题文本
    :param fallback: 无法判定时的归并分组
    :return: 单个大写字母或兜底分组
    """
    if not text:
        return fallback
    text = str(text).lstrip()
    for char in text:
        if char in _LATIN:
            return char.upper()
        if char in _DIGITS:
            return fallback
        if _is_cjk(char):
            letter = _gb18030_letter(char)
            if letter:
                return letter
        # 标点、空白、符号：继续看下一个字符
        continue
    return fallback


